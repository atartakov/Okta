"""Generate a deterministic synthetic workforce for the demo and tests.

No real people, no employer data. Re-run to regenerate fixtures/population.json:

    python scripts/gen_population.py > fixtures/population.json
"""
import hashlib
import json
import random

SEED = 20261010

DEPARTMENTS = {
    # department: (headcount, titles, cost centers)
    "Engineering": (400, ["Software Engineer", "Senior Software Engineer", "Staff Engineer", "SRE", "Engineering Manager"],
                    ["CC-100", "CC-110", "CC-120"]),
    "Sales": (250, ["Account Executive", "Sales Development Rep", "Regional Sales Manager"], ["CC-300"]),
    "Sales Operations": (40, ["Sales Operations Analyst", "Deal Desk Specialist"], ["CC-310"]),
    "Sales Engineering": (60, ["Solutions Engineer", "Senior Solutions Engineer"], ["CC-320"]),
    "Marketing": (120, ["Marketing Manager", "Content Strategist", "Demand Gen Manager"], ["CC-400"]),
    "IT": (50, ["IT Support Specialist", "Systems Administrator", "IT Manager"], ["CC-500"]),
    "Finance": (80, ["Accountant", "Financial Analyst", "Controller"], ["CC-600"]),
    "Human Resources": (60, ["HR Business Partner", "Recruiter", "People Ops Specialist"], ["CC-700"]),
    "Customer Success": (150, ["Customer Success Manager", "Support Engineer"], ["CC-800"]),
    "Legal": (30, ["Counsel", "Paralegal"], ["CC-900"]),
    "Clinical": (140, ["Clinical Specialist", "Respiratory Therapist", "Clinical Educator"], ["CC-950"]),
    "Product": (120, ["Product Manager", "Product Designer", "UX Researcher"], ["CC-200"]),
}
COUNTRIES = ["US", "US", "US", "US", "AU", "GB", "DE", "FR", "SG", "CA", "IE", "JP"]
FIRST = ["Alex", "Sam", "Jordan", "Taylor", "Casey", "Riley", "Morgan", "Jamie", "Avery", "Quinn", "Drew", "Rowan",
         "Elliot", "Hayden", "Kai", "Noor", "Priya", "Mateo", "Lena", "Hiro", "Aisha", "Tomas", "Ines", "Wei"]
LAST = ["Nguyen", "Smith", "Garcia", "Kim", "Patel", "Müller", "Rossi", "Okafor", "Silva", "Cohen", "Tanaka", "Brown",
        "Lopez", "Novak", "Haddad", "Larsen", "Chen", "Kowalski", "Murphy", "Singh"]

GROUPS = ["Everyone"] + list(DEPARTMENTS) + ["Salesforce-Users", "Salesforce-Admin", "AWS-Prod",
                                            "Okta-Helpdesk-Admins", "Contractors"]


def gid(name: str) -> str:
    """Stable fake Okta group id for a group name."""
    return "00g" + hashlib.sha256(name.encode()).hexdigest()[:17]


def main() -> None:
    rnd = random.Random(SEED)
    users = []
    n = 0
    for dept, (count, titles, ccs) in DEPARTMENTS.items():
        for i in range(count):
            n += 1
            first, last = rnd.choice(FIRST), rnd.choice(LAST)
            title = rnd.choice(titles)
            if dept == "Sales Operations" and i < 3:
                title = "Salesforce Administrator"
            if dept == "Sales" and i == 0:
                title = "VP Sales"
            if dept == "Sales" and 1 <= i <= 4:
                title = "Director, Sales"
            etype = "Contractor" if rnd.random() < 0.15 else "Employee"
            groups = ["Everyone", dept]
            if etype == "Contractor":
                groups.append("Contractors")
            # Two legacy hand-assigned Salesforce admins, the kind every tenant has.
            if dept == "Finance" and i < 2:
                groups.append("Salesforce-Admin")
            users.append({
                "id": f"00u{n:017d}",
                "login": f"{first.lower()}.{last.lower()}{n}@example.com",
                "status": "ACTIVE",
                "profile": {
                    "firstName": first, "lastName": last, "department": dept, "title": title,
                    "employeeType": etype, "costCenter": rnd.choice(ccs),
                    "countryCode": rnd.choice(COUNTRIES), "employeeNumber": str(100000 + n),
                },
                "groups": groups,
            })
    group_ids = {gid(name): name for name in GROUPS}
    comment = "Synthetic users generated by scripts/gen_population.py. Not real people."
    print('{"_comment": %s,\n "groups": %s,\n "users": [' % (json.dumps(comment), json.dumps(group_ids)))
    print(",\n".join("  " + json.dumps(u, ensure_ascii=False) for u in users))
    print(" ]\n}")


if __name__ == "__main__":
    main()
